/** Total mission duration: TJI + Jupiter-flyby departure leg, then 0.1 c cruise. */
export function transitYears(star: StarSystem): number {
  return totalYears(star.distanceLy);
}

/** Equatorial-rectangular position in parsecs, Sol at origin. */
export function starPosition(star: StarSystem): [number, number, number] {
  const d = star.distanceLy / 3.26156;
  const raDeg = star.ra * 15;
  const ra = (raDeg * Math.PI) / 180;
  const dec = (star.dec * Math.PI) / 180;
  return [
    d * Math.cos(dec) * Math.cos(ra),
    d * Math.sin(dec),
    d * Math.cos(dec) * Math.sin(ra),
  ];
}
